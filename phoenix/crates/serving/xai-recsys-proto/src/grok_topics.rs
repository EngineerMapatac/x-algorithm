pub fn ids_to_multihot(ids: &[i64], max_categories: usize) -> [bool; NUM_TOPICS] {
    let mut out = [false; NUM_TOPICS];
    if max_categories == 0 {
        return out;
    }
    let mut count = 0;
    for &id in ids {
        if let Some(i) = topic_index(id)
            && !out[i]
        {
            out[i] = true;
            count += 1;
            if count >= max_categories {
                break;
            }
        }
    }
    out
}

pub fn ids_to_bool_array<const N: usize>(ids: &[i64], known: &[i64; N]) -> [bool; N] {
    let mut out = [false; N];
    let set: std::collections::HashSet<i64> = ids.iter().copied().collect();
    for (i, &id) in known.iter().enumerate() {
        out[i] = set.contains(&id);
    }
    out
}
